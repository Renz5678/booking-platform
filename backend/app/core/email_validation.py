def _extract_domain(email: str) -> str:
    return email.strip().lower().rsplit("@", 1)[-1]


def is_disposable_domain(domain: str) -> bool:
    """Return True if domain or any parent domain is a known disposable email provider."""
    domain = domain.strip().lower().rstrip(".")
    if domain in DISPOSABLE_EMAIL_DOMAINS:
        return True
    parts = domain.split(".")
    for idx in range(1, len(parts) - 1):
        parent = ".".join(parts[idx:])
        if parent in DISPOSABLE_EMAIL_DOMAINS:
            return True
    return False


def assert_non_disposable_email(email: str) -> str:
    """
    Synchronous check for Pydantic validators:
    normalizes email and rejects known disposable domains and malformed domains.
    """
    normalized = email.strip().lower()
    if "@" not in normalized:
        raise ValueError("Invalid email address")
    domain = _extract_domain(normalized)
    if "." not in domain or domain.startswith(".") or domain.endswith("."):
        raise ValueError("Invalid email domain")
    if is_disposable_domain(domain):
        raise ValueError(
            "Disposable or temporary email addresses are not allowed. Please use a permanent email address."
        )
    if domain.endswith(RESERVED_TLDS):
        raise ValueError("Invalid or reserved email domain")
    if settings.ENVIRONMENT == "production" and domain in RESERVED_OR_FAKE_DOMAINS:
        raise ValueError("Please use a real email address")
    return normalized


@lru_cache(maxsize=512)
def _has_valid_mail_dns_sync(domain: str) -> bool:
    """
    Verify via DNS that `domain` can receive email:
      - Checks MX records first (rejecting RFC 7505 null MX '.').
      - Falls back to A/AAAA records per RFC 5321 if no MX record exists.
    """
    resolver = dns.resolver.Resolver()
    resolver.timeout = 2.0
    resolver.lifetime = 3.0

    try:
        mx_answers = resolver.resolve(domain, "MX")
        for rdata in mx_answers:
            exchange = str(rdata.exchange).strip()
            if exchange and exchange != ".":
                return True
        return False
    except (dns.resolver.NoAnswer, dns.resolver.NoNameservers):
        # Fallback to A/AAAA per RFC 5321
        for rtype in ("A", "AAAA"):
            try:
                answers = resolver.resolve(domain, rtype)
                if len(answers) > 0:
                    return True
            except dns.exception.DNSException:
                continue
        return False
    except dns.resolver.NXDOMAIN:
        return False
    except dns.exception.DNSException as exc:
        logger.warning("DNS lookup error for email domain %s: %s", domain, exc)
        return False


async def verify_email_deliverability(email: str, *, force_dns: bool = False) -> None:
    """
    Strict email verification gate for public endpoints:
      1. Rejects disposable and fake/reserved domains.
      2. In production (or when force_dns=True), verifies active MX / A DNS records.
    """
    try:
        normalized = assert_non_disposable_email(email)
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(exc),
        ) from exc

    domain = _extract_domain(normalized)
    if settings.ENVIRONMENT == "production" or force_dns:
        has_dns = await asyncio.to_thread(_has_valid_mail_dns_sync, domain)
        if not has_dns:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="This email domain cannot receive emails. Please use a valid, active email address.",
            )
